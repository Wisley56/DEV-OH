export const CARDS: Record<string, CardDef> = Object.fromEntries(list.map((c) => [c.id, c]));
export const CARD_LIST: CardDef[] = list;

export function card(id: string): CardDef {
  const c = CARDS[id];
  if (!c) throw new Error(`Card desconhecido: ${id}`);
  return c;
}

export function tributesNeeded(level: number): number {
  if (level >= 7) return 2;
  if (level >= 5) return 1;
  return 0;
}
